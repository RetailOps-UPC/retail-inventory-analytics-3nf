#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Renders the versioned data-quality report: ``docs/data_quality_report.md``.

Every ETL run appends one line to ``docs/data_quality/history.jsonl`` and writes
a full per-run record under ``data/quality_runs/`` (untracked). This script turns
the latest record plus the history into a readable report, so data quality has
both a current scorecard and a trend line, and both live under version control.

The report is regenerated from data, never edited by hand, and it states which
run it was built from, so a reader can always trace a number to a record.

Usage
-----
    python src/dq_report.py
    python src/dq_report.py --history docs/data_quality/history.jsonl --out docs/data_quality_report.md

Dependencies: Python 3.9+ standard library only.
Author: Odar Javier Alcocer Vásquez (Information Systems Engineering - UPC)
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional

sys.path.insert(0, str(Path(__file__).resolve().parent))
import dq  # noqa: E402

PROJECT_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUT = PROJECT_ROOT / "docs" / "data_quality_report.md"
TREND_ROWS = 10


def pct(value: Optional[float], digits: int = 2) -> str:
    return "n/a" if value is None else f"{100 * value:.{digits}f}%"


def latest_record(runs_dir: Path) -> Optional[Dict[str, Any]]:
    """The newest full run record that is not a dry run, falling back to any."""
    if not runs_dir.is_dir():
        return None
    records = []
    for path in sorted(runs_dir.glob("*.json"), reverse=True):
        try:
            records.append(json.loads(path.read_text(encoding="utf-8")))
        except (OSError, ValueError):
            continue
    for record in records:
        if not record.get("dry_run"):
            return record
    return records[0] if records else None


def render(record: Optional[Dict[str, Any]], history: List[Dict[str, Any]]) -> str:
    """Build the Markdown report. Pure: same inputs, same text."""
    lines: List[str] = []
    add = lines.append

    add("# Data quality report")
    add("")
    add("> Generated by `src/dq_report.py` from the ETL quality gate's run records. "
        "Do not edit by hand: every figure is recomputed on each run.")
    add("")

    if record is None and not history:
        add("No quality runs have been recorded yet. Run `make validate` or "
            "`python src/etl_pipeline.py --dry-run`.")
        return "\n".join(lines) + "\n"

    if record is not None:
        totals = record["totals"]
        source = record.get("source") or {}
        add("## Latest run")
        add("")
        add("| | |")
        add("|---|---|")
        add(f"| Run | `{record['run_id']}` |")
        add(f"| Recorded | {record['recorded_at']} |")
        add(f"| Mode | {'dry run (validate only)' if record['dry_run'] else 'full load'} |")
        add(f"| Status | **{record['status']}** |")
        if record.get("git_sha"):
            add(f"| Commit | `{record['git_sha']}` |")
        if source:
            add(f"| Data | synthetic, seed `{source.get('seed')}`, "
                f"{source.get('start_date')} to {source.get('end_date')} "
                f"({source.get('days')} days), policy `{source.get('policy')}` |")
        add(f"| Rows extracted | {totals['rows_extracted']:,} |")
        add(f"| Rows quarantined | {totals['rows_quarantined']:,} |")
        add(f"| **Acceptance rate** | **{pct(totals['acceptance_rate'], 3)}** |")
        add("")

        scores = record.get("dimension_scores") or {}
        if scores:
            add("## Scorecard by dimension")
            add("")
            add("A *row-check* is one row evaluated by one rule. A dimension's score is "
                "the share of its row-checks that passed.")
            add("")
            add("| Dimension | Row-checks | Failed | Pass rate |")
            add("|---|---:|---:|---:|")
            for dimension in dq.DIMENSIONS:
                if dimension in scores:
                    s = scores[dimension]
                    add(f"| {dimension} | {s['evaluated']:,} | {s['failed']:,} | "
                        f"{pct(s['pass_rate'], 3)} |")
            add("")

        truth = record.get("ground_truth") or []
        if truth:
            injected = sum(g["injected"] for g in truth)
            detected = sum(g["detected"] for g in truth)
            add("## Gate versus ground truth")
            add("")
            add("The synthetic generator records the natural key of every defect it "
                "plants. Scoring the gate against that list measures **recall** "
                "(how many planted defects it caught) instead of asserting that the "
                "checks work. A defect counts as caught only if the specific row was "
                "flagged by the rule responsible for it.")
            add("")
            add(f"**{detected} of {injected} planted defects caught "
                f"({pct(detected / injected if injected else None, 1)} recall).**")
            add("")
            add("| Planted defect | Rule | Planted | Caught | Recall | Other rows flagged |")
            add("|---|---|---:|---:|---:|---:|")
            for g in truth:
                add(f"| {g['kind']} | `{g['rule_id']}` | {g['injected']} | {g['detected']} "
                    f"| {pct(g['recall'], 0)} | {g['unexpected']} |")
            missed = [(g["kind"], m) for g in truth for m in g["missed"]]
            if missed:
                add("")
                add("**Missed:** " + ", ".join(f"`{k}` {m}" for k, m in missed))
            add("")
            add("*Other rows flagged* are rows the rule rejected that the generator did "
                "not plant. They are not automatically false positives: the simulation "
                "can produce a genuine instance of the same condition. Inspect them; "
                "do not read them as a precision score.")
            add("")

        rules = record.get("rules") or []
        if rules:
            add("## Every rule, including the ones that found nothing")
            add("")
            add("A rule with 0 failures still appears here, because \"no findings\" "
                "must be distinguishable from \"the rule never ran\".")
            add("")
            add("| Rule | Dataset | Dimension | Severity | Check | Evaluated | Failed | Pass rate |")
            add("|---|---|---|---|---|---:|---:|---:|")
            for r in sorted(rules, key=lambda x: (x["rule_id"], x["dataset"])):
                title = dq.RULES[r["rule_id"]].title if r["rule_id"] in dq.RULES else ""
                rate = 1 - r["failed"] / r["evaluated"] if r["evaluated"] else None
                add(f"| `{r['rule_id']}` | {r['dataset']} | {r['dimension']} | {r['severity']} "
                    f"| {title} | {r['evaluated']:,} | {r['failed']:,} | {pct(rate, 2)} |")
            add("")

        datasets = record.get("datasets") or {}
        quarantined = {k: v for k, v in datasets.items() if v["quarantined"]}
        if quarantined:
            add("## Quarantine by dataset")
            add("")
            add("Rows an ERROR-severity rule rejected. They are written to "
                "`data/quarantine/` with the rule that rejected them, never silently "
                "corrected into the warehouse.")
            add("")
            add("| Dataset | Extracted | Quarantined | Share |")
            add("|---|---:|---:|---:|")
            for name, v in quarantined.items():
                add(f"| {name} | {v['extracted']:,} | {v['quarantined']:,} | "
                    f"{pct(v['quarantined'] / v['extracted'], 2)} |")
            add("")

    # Every run belongs on the trend, dry or not: the Mode column says which. A
    # dry run scores the same gate on a different seed, which is exactly the
    # evidence that recall is not an accident of one dataset.
    real = sorted(history, key=lambda h: h["recorded_at"])
    if real:
        add(f"## Trend (last {min(len(real), TREND_ROWS)} runs)")
        add("")
        add("| Recorded | Mode | Seed | Window end | Rows | Quarantined | Acceptance | Caught |")
        add("|---|---|---:|---|---:|---:|---:|---:|")
        for h in real[-TREND_ROWS:]:
            src = h.get("source") or {}
            truth = h.get("ground_truth") or {}
            inj = sum(v["injected"] for v in truth.values())
            det = sum(v["detected"] for v in truth.values())
            caught = f"{det}/{inj}" if inj else "-"
            add(f"| {h['recorded_at']} | {'dry' if h.get('dry_run') else 'load'} "
                f"| {src.get('seed', '-')} | {src.get('end_date', '-')} "
                f"| {h['totals']['rows_extracted']:,} | {h['totals']['rows_quarantined']:,} "
                f"| {pct(h['totals']['acceptance_rate'], 3)} | {caught} |")
        add("")

    add("## How to read this report")
    add("")
    add("- **Acceptance rate** is the share of extracted rows that passed every "
        "ERROR-severity rule. It is a cleanliness measure of the *source*, not of the "
        "warehouse: quarantined rows never reach the warehouse at all.")
    add("- **Ground truth exists only for synthetic data.** Recall here is measured "
        "against the defects the generator planted. It says nothing about defects "
        "nobody thought to plant; against real data there is no list to score against.")
    add("- **Severity decides the reaction.** FATAL aborts the run, ERROR quarantines "
        "the offending rows, WARNING is reported and the rows still load.")
    add("")
    return "\n".join(lines) + "\n"


def generate(history_path: Path = dq.DEFAULT_HISTORY_PATH,
             runs_dir: Path = dq.DEFAULT_RUNS_DIR,
             out_path: Path = DEFAULT_OUT) -> Path:
    """Read the quality records and write the report. Returns the path written."""
    text = render(latest_record(runs_dir), dq.read_history(history_path))
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(text, encoding="utf-8", newline="\n")
    return out_path


def parse_args(argv: Optional[List[str]] = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Render the data-quality report.")
    parser.add_argument("--history", type=Path, default=dq.DEFAULT_HISTORY_PATH)
    parser.add_argument("--runs-dir", type=Path, default=dq.DEFAULT_RUNS_DIR)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    return parser.parse_args(argv)


def main(argv: Optional[List[str]] = None) -> int:
    args = parse_args(argv)
    path = generate(args.history, args.runs_dir, args.out)
    print(f"Wrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
